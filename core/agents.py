class JarvisOrchestrator:
    def __init__(self):
        self.zero = AgentZero()
        self.hermes = Hermes()
        self.xbow = XBow()
        self.openclaw = OpenClaw()
        self.graph = self._build_graph()

    def _build_graph(self):
        wf = StateGraph(AgentState)
        wf.add_node("plan", self._plan_node)
        wf.add_node("execute", self._execute_node)
        wf.add_node("analyze", self._analyze_node)
        wf.add_node("remember", self._remember_node)
        wf.add_node("report", self._report_node)

        wf.set_entry_point("plan")
        wf.add_edge("plan", "execute")
        wf.add_edge("execute", "analyze")
        wf.add_edge("analyze", "remember")
        wf.add_conditional_edges(
            "remember",
            self._should_continue,
            {"continue": "plan", "complete": "report"},
        )
        wf.add_edge("report", END)
        return wf.compile()

    def _plan_node(self, state):
        plan = self.xbow.plan_attack(state)
        state["messages"].append(plan)
        return state

    def _execute_node(self, state):
        plan = state["messages"][-1]
        result = self.xbow.execute_tool_call(plan, state)
        state["messages"].append(f"RESULT: {json.dumps(result)[:3000]}")
        return state

    def _analyze_node(self, state):
        last = state["messages"][-1]
        prompt = f"""
Extract findings. Always English for report fields:
FINDING: <english title>
SEVERITY: <Critical|High|Medium|Low|Info>
EVIDENCE: <evidence>
REMEDIATION: <fix>
PORT: <num>
SERVICE: <name>

Output: {last}
"""
        analysis = self.xbow.think(prompt, lang="Respond in English.")
        state["messages"].append(analysis)
        state["findings"].extend(self._parse_findings(analysis))
        state["open_ports"].extend(self._parse_ports(analysis))
        state["iteration"] += 1
        return state

    def _remember_node(self, state):
        self.zero.save_memory(state, "last_target", state.get("target"))
        return state

    def _report_node(self, state):
        state["messages"].append("REPORT_PENDING: report_generator will handle")
        return state

    def _should_continue(self, state):
        if state.get("iteration", 0) >= CONFIG["max_iterations"]:
            return "complete"
        if state["messages"] and "MISSION_COMPLETE" in state["messages"][-1]:
            return "complete"
        return "continue"

    def _parse_findings(self, text):
        findings = []
        for block in re.split(r"(?=FINDING:)", text):
            if "FINDING:" not in block:
                continue
            f = {}
            for field in ["FINDING", "SEVERITY", "EVIDENCE", "REMEDIATION"]:
                m = re.search(rf"{field}:\s*(.+)", block)
                if m:
                    f[field.lower()] = m.group(1).strip()
            if f:
                findings.append(f)
        return findings

    def _parse_ports(self, text):
        ports = []
        for block in re.split(r"(?=PORT:)", text):
            if "PORT:" not in block:
                continue
            p = {}
            for field in ["PORT", "SERVICE"]:
                m = re.search(rf"{field}:\s*(.+)", block)
                if m:
                    p[field.lower()] = m.group(1).strip()
            if p:
                ports.append(p)
        return ports

    def run_mission(self, target: str):
        memory = self.zero.load_memory()
        state = AgentState(target=target, phase="recon", memory=memory)
        return self.graph.invoke(state)

    def analyze_source(self, path: str):
        from pathlib import Path
        p = Path(path)
        files = [p] if p.is_file() else [f for f in p.rglob("*") if f.is_file()][:100]

        code = ""
        for f in files:
            if f.suffix in [".py", ".js", ".ts", ".php", ".java", ".go",
                            ".rb", ".c", ".cpp", ".rs", ".sh", ".sql", ".html"]:
                try:
                    code += f"\n=== {f} ===\n{f.read_text(errors='ignore')[:2500]}"
                except Exception:
                    pass

        prompt = f"""
Security analysis (English output only for findings):
{code[:15000]}

Find: SQLi, XSS, RCE, SSRF, LFI, auth flaws, secrets, deserialization.
For each: file, severity, evidence, remediation.
"""
        return self.xbow.think(prompt, lang="Respond in English only.")