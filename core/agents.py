class XBow(BaseAgent):
    def __init__(self):
        super().__init__(
            "XBow",
            """You are XBOW, offensive security agent.
Plan attack chains. Choose RIGHT tool.

Tools: nmap, metasploit, burp, sqlmap, gobuster, ffuf, nuclei,
wpscan, hashcat, john, hydra, commix, nikto, searchsploit,
crackmapexec, bloodhound, etc.

Output STRICT:
TOOL: <tool>
ARGS: <json array>
TARGET: <target>
REASON: <why>

When done:
MISSION_COMPLETE
SUMMARY: <text>
""",
        )

    def plan_attack(self, state):
        context = f"""
Target: {state.get('target')}
Phase: {state.get('phase')}
Ports: {state.get('open_ports', [])}
Findings: {json.dumps(state.get('findings', []), indent=2)[:2000]}
Exploits tried: {state.get('exploits_tried', [])}
Iteration: {state.get('iteration', 0)}/{CONFIG['max_iterations']}
Next action?
"""
        return self.think(context)

    def execute_tool_call(self, llm_output: str, state: AgentState) -> Dict:
        """
        Parse LLM output and execute tool.

        FIX: `result` is ALWAYS defined before return.
        Original bug: result only assigned in msf branch → UnboundLocalError.
        """
        tool_match = re.search(r"TOOL:\s*(\S+)", llm_output)
        if not tool_match:
            return {"success": False, "error": "No tool call found in LLM output"}

        tool = tool_match.group(1).strip()

        args_match = re.search(r"ARGS:\s*(\[.*?\])", llm_output, re.DOTALL)
        try:
            args = json.loads(args_match.group(1)) if args_match else []
        except json.JSONDecodeError:
            args = []

        target_match = re.search(r"TARGET:\s*(\S+)", llm_output)
        target = target_match.group(1) if target_match else state.get("target", "")

        # Default nmap args
        if tool == "nmap" and not args and target:
            args = ["-sV", "-sC", "-T4", target]

        # ─── EXECUTE — single path, always assigned ────────
        result = RemoteToolExecutor.execute(tool, args, target)

        # ─── Track exploits (safe, after result defined) ──
        if tool in ("metasploit-framework", "msfconsole", "searchsploit"):
            state.setdefault("exploits_tried", []).append({
                "tool": tool,
                "args": args,
                "success": result.get("success", False),
            })

        return result


