class AgentZero(BaseAgent):
    def __init__(self):
        super().__init__(
            "AgentZero",
            "You are AGENT ZERO. Coordinate agents, maintain memory, create tools.",
        )

    def save_memory(self, state, key, value):
        state["memory"][key] = value
        mem_file = CONFIG["workspace"] / "agent_zero_memory.json"
        try:
            mem_file.write_text(json.dumps(state["memory"], indent=2, default=str))
        except Exception:
            pass

    def load_memory(self):
        mem_file = CONFIG["workspace"] / "agent_zero_memory.json"
        if mem_file.exists():
            try:
                return json.loads(mem_file.read_text())
            except Exception:
                return {}
        return {}

    def create_tool(self, name: str, language: str, code: str):
        """
        Save LLM-generated tool — QUARANTINED, not executable.

        FIX: chmod 0o755 REMOVED.
        Reason: LLM can hallucinate dangerous code (rm -rf, exfil).
                Operator must review before execution.
        """
        if not CONFIG.get("allow_custom_tools", False):
            console.print("[yellow][!] Custom tools disabled "
                          "(set allow_custom_tools=True in config)[/yellow]")
            return None

        tools_dir = CONFIG["custom_tools_dir"]
        tools_dir.mkdir(parents=True, exist_ok=True)
        ext = ".py" if language == "python" else ".sh"
        tool_path = tools_dir / f"{name}{ext}"

        # Safety header for human reviewer
        header = (
            "# ═══════════════════════════════════════════════════════\n"
            "# ⚠️  LLM-GENERATED CODE — QUARANTINED\n"
            "# ═══════════════════════════════════════════════════════\n"
            "# This file was generated by an LLM and is NOT executable.\n"
            "# REVIEW the code carefully before running.\n"
            "# To enable execution:\n"
            "#   1. Read the entire file\n"
            "#   2. Verify NO dangerous operations (rm -rf, exfil, etc.)\n"
            "#   3. Run: chmod +x <file>\n"
            "# ═══════════════════════════════════════════════════════\n\n"
        )
        tool_path.write_text(header + code)

        # READ-ONLY for owner (no execute bit)
        tool_path.chmod(0o644)

        console.print(f"[yellow][!] Tool quarantined: {tool_path}[/yellow]")
        console.print("[yellow][!] Review, then manually `chmod +x` to run[/yellow]")
        return str(tool_path)


