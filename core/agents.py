class OpenClaw(BaseAgent):
    def __init__(self):
        super().__init__(
            "OpenClaw",
            "You are OPENCLAW. Parse voice commands, generate summaries.",
        )

    def voice_summary(self, state):
        findings = state.get("findings", [])
        critical = [f for f in findings if f.get("severity") == "Critical"]
        lang = CONFIG["language"]
        if lang == "hinglish":
            return f"Mission complete. Total {len(findings)} findings. {len(critical)} critical."
        elif lang == "roman_urdu":
            return f"Mission mukammal. {len(findings)} findings. {len(critical)} critical."
        return f"Mission complete. Total: {len(findings)}. Critical: {len(critical)}."


