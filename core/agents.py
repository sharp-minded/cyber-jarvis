console = Console()


class AgentState(dict):
    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        self.setdefault("messages", [])
        self.setdefault("target", "")
        self.setdefault("phase", "recon")
        self.setdefault("findings", [])
        self.setdefault("iteration", 0)
        self.setdefault("memory", {})
        self.setdefault("open_ports", [])
        self.setdefault("exploits_tried", [])


class BaseAgent:
    def __init__(self, name: str, system_prompt: str):
        self.name = name
        self.system_prompt = system_prompt
        self.llm = self._init_llm()

    def _init_llm(self):
        return ChatOpenAI(
            model=CONFIG["model"],
            temperature=CONFIG["temperature"],
            api_key=CONFIG["deepseek_api_key"],
            base_url=CONFIG["deepseek_base_url"],
        )

    def think(self, prompt: str, extra_context: str = "", lang: str = None) -> str:
        lang_instruction = get_language_prompt() if lang is None else lang
        full_system = f"{self.system_prompt}\n\nLanguage: {lang_instruction}"
        messages = [
            SystemMessage(content=full_system),
            HumanMessage(content=f"{extra_context}\n\n{prompt}"),
        ]
        return self.llm.invoke(messages).content


